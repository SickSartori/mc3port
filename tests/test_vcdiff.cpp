bool decode(const std::vector<uint8_t>& delta, const std::vector<uint8_t>& source, std::vector<uint8_t>& target,
            std::string& error) {
    target.clear();
    return vcdiff_decode(
        delta.data(), delta.size(),
        [&](uint64_t offset, uint8_t* out, size_t size) {
            if (offset + size > source.size()) return false;
            std::memcpy(out, source.data() + offset, size);
            return true;
        },
        [&](const uint8_t* data, size_t size) {
            target.insert(target.end(), data, data + size);
            return true;
        },
        &error);
}


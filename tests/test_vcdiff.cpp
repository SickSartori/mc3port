int main() {
    const std::vector<uint8_t> source = pseudo_random(70000, 1);
    std::vector<uint8_t> expected(source.begin(), source.begin() + 20000);
    for (int i = 0; i < 40; ++i) {
        const char* text = "Traducao: Joao13 e cia. ";
        expected.insert(expected.end(), text, text + std::strlen(text));
    }
    expected.insert(expected.end(), source.begin() + 25000, source.begin() + 50000);
    expected.insert(expected.end(), 3000, 0);
    expected.insert(expected.end(), source.begin() + 52000, source.end());
    expected.insert(expected.end(), source.begin() + 100, source.begin() + 5100);

    const std::vector<uint8_t> delta(std::begin(kDelta), std::end(kDelta));
    std::vector<uint8_t> target;
    std::string error;
    CHECK(decode(delta, source, target, error));
    CHECK(target == expected);

    // Damaged: cut short, a wrong magic, secondary compression asked for.
    std::vector<uint8_t> cut(delta.begin(), delta.begin() + static_cast<ptrdiff_t>(delta.size() / 2));
    CHECK(!decode(cut, source, target, error));
    std::vector<uint8_t> magic = delta;
    magic[0] = 0;
    CHECK(!decode(magic, source, target, error) && error == "not a VCDIFF delta");
    std::vector<uint8_t> secondary = delta;
    secondary[4] |= 1;
    CHECK(!decode(secondary, source, target, error));
    // A source too short to read from.
    const std::vector<uint8_t> short_source(source.begin(), source.begin() + 1000);
    CHECK(!decode(delta, short_source, target, error));
    return test_result();
}
